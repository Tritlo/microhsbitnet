module FloatWGSL (wgslPrelude, softFloat) where

import System.IO.Unsafe (unsafePerformIO)

-- | Software binary64 and an exponential checked by check-float.py.
softFloat :: String
{-# NOINLINE softFloat #-}
softFloat = unsafePerformIO (readFile "spike/ccc/float_soft.wgsl")

-- | Provide binary32 multiplication, division, and square root with integer significands.
wgslPrelude :: String
wgslPrelude =
    softFloat
        ++ unlines
            [ "fn multiply32(left: f32, right: f32) -> f32 {"
            , "  let leftBits = bitcast<u32>(left);"
            , "  let rightBits = bitcast<u32>(right);"
            , "  let sign = (leftBits ^ rightBits) & 0x80000000u;"
            , "  let leftExponent = (leftBits >> 23u) & 255u;"
            , "  let rightExponent = (rightBits >> 23u) & 255u;"
            , "  var first = leftBits & 0x7fffffu;"
            , "  var second = rightBits & 0x7fffffu;"
            , "  if (leftExponent == 255u || rightExponent == 255u) {"
            , "    if ((leftExponent == 255u && first != 0u) || (rightExponent == 255u && second != 0u) || (leftBits & 0x7fffffffu) == 0u || (rightBits & 0x7fffffffu) == 0u) { return bitcast<f32>(sign | 0x7fc00000u); }"
            , "    return bitcast<f32>(sign | 0x7f800000u);"
            , "  }"
            , "  if ((leftBits & 0x7fffffffu) == 0u || (rightBits & 0x7fffffffu) == 0u) { return bitcast<f32>(sign); }"
            , "  var firstExponent = i32(leftExponent) - 127;"
            , "  var secondExponent = i32(rightExponent) - 127;"
            , "  if (leftExponent == 0u) { firstExponent = -126; } else { first |= 0x800000u; }"
            , "  if (rightExponent == 0u) { secondExponent = -126; } else { second |= 0x800000u; }"
            , "  while (first < 0x800000u) { first <<= 1u; firstExponent--; }"
            , "  while (second < 0x800000u) { second <<= 1u; secondExponent--; }"
            , "  let lowProduct = (first & 65535u) * (second & 65535u);"
            , "  let cross = (first >> 16u) * (second & 65535u) + (first & 65535u) * (second >> 16u);"
            , "  let low = lowProduct + (cross << 16u);"
            , "  let high = (first >> 16u) * (second >> 16u) + (cross >> 16u) + select(0u, 1u, low < lowProduct);"
            , "  var exponent = firstExponent + secondExponent;"
            , "  var shift = 23u;"
            , "  if ((high & 0x8000u) != 0u) { shift = 24u; exponent++; }"
            , "  if (exponent > 127) { return bitcast<f32>(sign | 0x7f800000u); }"
            , "  if (exponent < -126) { shift += u32(-126 - exponent); }"
            , "  if (shift > 48u) { return bitcast<f32>(sign); }"
            , "  var significand = 0u;"
            , "  var above = false;"
            , "  var halfway = false;"
            , "  if (shift < 32u) {"
            , "    significand = (high << (32u - shift)) | (low >> shift);"
            , "    let discarded = low & ((1u << shift) - 1u);"
            , "    let midpoint = 1u << (shift - 1u);"
            , "    above = discarded > midpoint; halfway = discarded == midpoint;"
            , "  } else if (shift == 32u) {"
            , "    significand = high; above = low > 0x80000000u; halfway = low == 0x80000000u;"
            , "  } else {"
            , "    significand = high >> (shift - 32u);"
            , "    let discarded = high & ((1u << (shift - 32u)) - 1u);"
            , "    let midpoint = 1u << (shift - 33u);"
            , "    above = discarded > midpoint || (discarded == midpoint && low != 0u); halfway = discarded == midpoint && low == 0u;"
            , "  }"
            , "  if (above || (halfway && (significand & 1u) != 0u)) { significand++; }"
            , "  if (exponent < -126) { return bitcast<f32>(sign | significand); }"
            , "  if (significand == 0x1000000u) { significand >>= 1u; exponent++; }"
            , "  if (exponent > 127) { return bitcast<f32>(sign | 0x7f800000u); }"
            , "  return bitcast<f32>(sign | (u32(exponent + 127) << 23u) | (significand & 0x7fffffu));"
            , "}"
            , "fn sqrt32(input: f32) -> f32 {"
            , "  let bits = bitcast<u32>(input);"
            , "  if ((bits & 0x7fffffffu) == 0u) { return input; }"
            , "  if ((bits & 0x80000000u) != 0u) { return bitcast<f32>((bits & 1u) | 0x7fc00000u); }"
            , "  let rawExponent = (bits >> 23u) & 255u;"
            , "  if (rawExponent == 255u) { return input; }"
            , "  var significand = bits & 0x7fffffu;"
            , "  var exponent = i32(rawExponent) - 127;"
            , "  if (rawExponent == 0u) { exponent = -126; } else { significand |= 0x800000u; }"
            , "  while (significand < 0x800000u) { significand <<= 1u; exponent--; }"
            , "  if ((exponent % 2) != 0) { significand <<= 1u; exponent--; }"
            , "  exponent /= 2;"
            , "  let high = significand >> 9u;"
            , "  let low = significand << 23u;"
            , "  var root = 0u;"
            , "  var remainder = 0u;"
            , "  for (var index = 0u; index < 24u; index++) {"
            , "    let bit = 46u - index * 2u;"
            , "    var pair = 0u;"
            , "    if (bit >= 32u) { pair = (high >> (bit - 32u)) & 3u; } else { pair = (low >> bit) & 3u; }"
            , "    remainder = (remainder << 2u) | pair;"
            , "    let trial = (root << 2u) | 1u;"
            , "    root <<= 1u;"
            , "    if (remainder >= trial) { remainder -= trial; root |= 1u; }"
            , "  }"
            , "  if (remainder > root) { root++; }"
            , "  if (root == 0x1000000u) { root >>= 1u; exponent++; }"
            , "  return bitcast<f32>((u32(exponent + 127) << 23u) | (root & 0x7fffffu));"
            , "}"
            , "fn divide32(left: f32, right: f32) -> f32 {"
            , "  let leftBits = bitcast<u32>(left);"
            , "  let rightBits = bitcast<u32>(right);"
            , "  let sign = (leftBits ^ rightBits) & 0x80000000u;"
            , "  let leftExponent = (leftBits >> 23u) & 255u;"
            , "  let rightExponent = (rightBits >> 23u) & 255u;"
            , "  var numerator = leftBits & 0x7fffffu;"
            , "  var denominator = rightBits & 0x7fffffu;"
            , "  if (leftExponent == 255u || rightExponent == 255u) {"
            , "    if ((leftExponent == 255u && numerator != 0u) || (rightExponent == 255u && denominator != 0u) || (leftExponent == 255u && rightExponent == 255u)) { return bitcast<f32>(sign | 0x7fc00000u); }"
            , "    if (leftExponent == 255u) { return bitcast<f32>(sign | 0x7f800000u); }"
            , "    return bitcast<f32>(sign);"
            , "  }"
            , "  if ((rightBits & 0x7fffffffu) == 0u) {"
            , "    if ((leftBits & 0x7fffffffu) == 0u) { return bitcast<f32>(sign | 0x7fc00000u); }"
            , "    return bitcast<f32>(sign | 0x7f800000u);"
            , "  }"
            , "  if ((leftBits & 0x7fffffffu) == 0u) { return bitcast<f32>(sign); }"
            , "  var numeratorExponent = i32(leftExponent) - 127;"
            , "  var denominatorExponent = i32(rightExponent) - 127;"
            , "  if (leftExponent == 0u) { numeratorExponent = -126; } else { numerator |= 0x800000u; }"
            , "  if (rightExponent == 0u) { denominatorExponent = -126; } else { denominator |= 0x800000u; }"
            , "  while (numerator < 0x800000u) { numerator <<= 1u; numeratorExponent--; }"
            , "  while (denominator < 0x800000u) { denominator <<= 1u; denominatorExponent--; }"
            , "  var exponent = numeratorExponent - denominatorExponent;"
            , "  if (numerator < denominator) { numerator <<= 1u; exponent--; }"
            , "  var remainder = numerator - denominator;"
            , "  if (exponent > 127) { return bitcast<f32>(sign | 0x7f800000u); }"
            , "  if (exponent < -150) { return bitcast<f32>(sign); }"
            , "  if (exponent == -150) { return bitcast<f32>(sign | select(0u, 1u, remainder != 0u)); }"
            , "  var bits = 23;"
            , "  if (exponent < -126) { bits = exponent + 149; }"
            , "  var significand = 1u;"
            , "  for (var index = 0; index < bits; index++) {"
            , "    remainder <<= 1u;"
            , "    significand <<= 1u;"
            , "    if (remainder >= denominator) { remainder -= denominator; significand |= 1u; }"
            , "  }"
            , "  let doubled = remainder << 1u;"
            , "  if (doubled > denominator || (doubled == denominator && (significand & 1u) != 0u)) { significand++; }"
            , "  if (exponent < -126) { return bitcast<f32>(sign | significand); }"
            , "  if (significand == 0x1000000u) { significand >>= 1u; exponent++; }"
            , "  if (exponent > 127) { return bitcast<f32>(sign | 0x7f800000u); }"
            , "  return bitcast<f32>(sign | (u32(exponent + 127) << 23u) | (significand & 0x7fffffu));"
            , "}"
            ]
